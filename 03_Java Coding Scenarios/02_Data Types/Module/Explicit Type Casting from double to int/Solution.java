class Main {
    public static void main(String[] args) {
        double a = 5.75; // You can change this value for testing

        // Perform explicit type casting from double to int
        int b = (int)a;

        // Print the original double and casted integer values
        System.out.println("Original double: " + a);
        System.out.println("Casted integer: " + b);
    }
}